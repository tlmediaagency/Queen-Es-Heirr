// Builds js/search-index.js from the site's HTML pages (title, description, headline, FAQ questions).
// Run after adding or editing pages:  node scripts/build-search-index.mjs
import fs from "node:fs"; import path from "node:path";
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const SKIP = new Set(["404.html", "order-confirmed/index.html", "wholesale/portal/index.html", "stories/post/index.html", "support/index.html"]);
const decode = (s) => s.replace(/&amp;/g, "&").replace(/&#39;|&rsquo;|&apos;/g, "'").replace(/&quot;/g, '"').replace(/&nbsp;/g, " ").replace(/&lt;/g, "<").replace(/&gt;/g, ">");
const text = (h) => decode(h.replace(/<script[\s\S]*?<\/script>/g, " ").replace(/<style[\s\S]*?<\/style>/g, " ").replace(/<[^>]+>/g, " ")).replace(/\s+/g, " ").trim();
const files = [];
(function walk(d) { for (const f of fs.readdirSync(d, { withFileTypes: true })) { if (["node_modules", "worker", ".git", "apps-script", "scripts", "js", "css", "images"].includes(f.name)) continue; const p = path.join(d, f.name); if (f.isDirectory()) walk(p); else if (f.name.endsWith(".html")) files.push(p); } })(ROOT);
const out = [];
for (const f of files.sort()) {
  const rel = path.relative(ROOT, f).replace(/\\/g, "/");
  if (SKIP.has(rel)) continue;
  const html = fs.readFileSync(f, "utf8");
  const url = "/" + rel.replace(/index\.html$/, "");
  const title = decode((html.match(/<title>([\s\S]*?)<\/title>/) || [])[1] || "").replace(/\s*[|–-]\s*Queen E's Heirr.*$/i, "").trim();
  const desc = decode((html.match(/<meta name="description" content="([^"]*)"/) || [])[1] || "");
  const main = (html.match(/<main[\s\S]*?<\/main>/) || [html])[0];
  const h1 = text((main.match(/<h1[^>]*>([\s\S]*?)<\/h1>/) || [])[1] || "");
  const heads = [...main.matchAll(/<h[23][^>]*>([\s\S]*?)<\/h[23]>/g)].map((m) => text(m[1])).filter((x) => x && x.length < 90 && !/^Your Bag$|^Queen E's Heirr$/.test(x)).slice(0, 14).join(" ");
  if (!title) continue;
  out.push(["page", url, title, desc, (h1 + " " + heads).trim()]);
  for (const m of main.matchAll(/<details[^>]*><summary>([\s\S]*?)<\/summary>([\s\S]*?)<\/details>/g)) {
    const q = text(m[1]), a = text(m[2]);
    if (q) out.push(["faq", url, q, a.slice(0, 220), a.slice(0, 600)]);
  }
}
fs.writeFileSync(path.join(ROOT, "js/search-index.js"), "/* Generated by scripts/build-search-index.mjs. Do not edit by hand. */\nwindow.SITE_SEARCH = " + JSON.stringify(out) + ";\n");
console.log("entries:", out.length, "pages:", out.filter((x) => x[0] === "page").length);
